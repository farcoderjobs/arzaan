import * as React from "react";

interface IconProps extends React.SVGAttributes<SVGSVGElement> {
  size?: number;
}

/**
 * Icons previously emitted `h-{size} w-{size}` Tailwind classes by default.
 * Those collided with the caller's own sizing classes (e.g. `h-4 w-4`), and
 * because Tailwind ships `.w-20` (used elsewhere in the codebase) the icon
 * could render 80px wide — sliding the glyph over adjacent text such as a
 * search input's placeholder. Size is now applied via inline style ONLY when
 * the caller did not provide their own sizing classes, so the two never fight.
 */
function iconProps({ className, size = 20, style, ...rest }: IconProps) {
  const callerSizes = /\b(?:h|w)-/.test(className ?? "");
  return {
    ...rest,
    className,
    style: callerSizes ? style : { width: size, height: size, ...style },
  };
}

